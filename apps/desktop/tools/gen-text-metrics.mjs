#!/usr/bin/env node
// Generates crates/zen-build/src/text_metrics.rs from the pinned
// circuit-to-svg package. The viewer sizes net-label flags with its own
// per-glyph table (arialTextMetrics) and flag formula; the Rust layout must
// reserve exactly that much space or labels overlap neighbors the checker
// can't see. Extracted from the bundle source (the table isn't exported).
// Run `pnpm gen:text-metrics` after bumping circuit-to-svg; `--check`
// (used in CI) fails when the checked-in table drifts.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const distPath = require.resolve("circuit-to-svg").replace(/dist\/.*$/, "dist/index.js");
const src = readFileSync(distPath, "utf8");

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../../../crates/zen-build/src/text_metrics.rs",
);

// --- extract the arialTextMetrics object literal --------------------------
const start = src.indexOf("var arialTextMetrics = {");
if (start < 0) throw new Error("arialTextMetrics not found in circuit-to-svg dist");
const braceStart = src.indexOf("{", start);
let depth = 0;
let end = braceStart;
for (; end < src.length; end++) {
  if (src[end] === "{") depth++;
  else if (src[end] === "}") {
    depth--;
    if (depth === 0) break;
  }
}
// The literal is plain data (string keys, numeric fields) — evaluate it.
const metrics = new Function(`return ${src.slice(braceStart, end + 1)}`)();

// --- extract the flag-geometry constants ----------------------------------
const constant = (name) => {
  const m = src.match(new RegExp(`var ${name} = ([0-9.]+);`));
  if (!m) throw new Error(`${name} not found in circuit-to-svg dist`);
  return Number(m[1]);
};
const ARROW = constant("ARROW_POINT_WIDTH_FSR");
const END_PAD = constant("END_PADDING_FSR");
const END_PAD_PER_CHAR = constant("END_PADDING_EXTRA_PER_CHARACTER_FSR");
const HEIGHT = constant("NET_LABEL_HEIGHT_MM");
const fontMatch = src.match(/net_label: ([0-9.]+)/);
if (!fontMatch) throw new Error("net_label font size not found");
const FONT = Number(fontMatch[1]);

const num = (v) => {
  const s = String(Math.round(v * 1e6) / 1e6);
  return s.includes(".") || s.includes("e") ? s : s + ".0";
};

// Advance widths in em (the table is drawn at a 27px em, exactly as the
// renderer divides). Escape for a Rust char literal.
const escapeChar = (c) =>
  c === "'" ? "\\'" : c === "\\" ? "\\\\" : c;
const entries = Object.entries(metrics)
  .filter(([k]) => k.length === 1)
  .map(([k, v]) => `    ('${escapeChar(k)}', ${num(v.width / 27)}),`)
  .join("\n");
const fallback = num(metrics["?"].width / 27);

const rust = `//! GENERATED by apps/desktop/tools/gen-text-metrics.mjs — do not edit.
//! Regenerate with \`pnpm gen:text-metrics\` after bumping circuit-to-svg.
//!
//! The viewer sizes net-label flags from its own per-glyph table
//! (arialTextMetrics, 27px em) and this exact formula; the layout reserves
//! the same space so flags never overlap what the checker can't see.

/// Per-character advance width in em units.
static CHAR_WIDTHS: &[(char, f64)] = &[
${entries}
];

const FALLBACK_EM: f64 = ${fallback};

/// Net-label font size in schematic units (circuit-to-svg fontSizeMap).
pub(crate) const NET_LABEL_FONT_SIZE: f64 = ${num(FONT)};
/// Net-label flag body height in schematic units.
pub(crate) const NET_LABEL_HEIGHT: f64 = ${num(HEIGHT)};

const ARROW_POINT_WIDTH_FSR: f64 = ${num(ARROW)};
const END_PADDING_FSR: f64 = ${num(END_PAD)};
const END_PADDING_EXTRA_PER_CHARACTER_FSR: f64 = ${num(END_PAD_PER_CHAR)};

/// Text width in em units (sum of advances; unknown chars fall back like
/// the renderer does).
pub(crate) fn text_width_em(text: &str) -> f64 {
    text.chars()
        .map(|c| {
            CHAR_WIDTHS
                .iter()
                .find(|(k, _)| *k == c)
                .map_or(FALLBACK_EM, |(_, w)| *w)
        })
        .sum()
}

/// Total rendered length of a net-label flag in schematic units — the
/// renderer's fullWidthFsr * font size, verbatim.
pub(crate) fn net_label_len(text: &str) -> f64 {
    let full = text_width_em(text)
        + ARROW_POINT_WIDTH_FSR * 2.0
        + END_PADDING_EXTRA_PER_CHARACTER_FSR * text.chars().count() as f64
        + END_PADDING_FSR;
    full * NET_LABEL_FONT_SIZE
}
`;

const check = process.argv.includes("--check");
if (check) {
  const current = readFileSync(OUT, "utf8");
  if (current !== rust) {
    console.error("text_metrics.rs is stale — run `pnpm gen:text-metrics`");
    process.exit(1);
  }
  console.log("text_metrics.rs is up to date");
} else {
  writeFileSync(OUT, rust);
  console.log(`wrote ${OUT}`);
}
