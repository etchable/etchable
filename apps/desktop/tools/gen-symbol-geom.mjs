#!/usr/bin/env node
// Generates crates/zen-build/src/symbol_geom.rs from the pinned
// schematic-symbols package. The viewer aligns glyphs to our emitted
// schematic_ports by angle-matching, so the Rust emitter must reproduce each
// symbol's native port geometry exactly — this table is that single source
// of truth. Run `pnpm gen:symbol-geom` after bumping schematic-symbols;
// `--check` (used in CI) fails when the checked-in table drifts.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { symbols } from "schematic-symbols";

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../../../crates/zen-build/src/symbol_geom.rs",
);

// Curated bases the emitter may map component types onto. Orientation
// variants are discovered from the package (many bases ship only horz/vert).
const BASES = [
  "battery",
  "boxresistor",
  "capacitor",
  "crystal",
  "diode",
  "ferrite_bead",
  "fuse",
  "inductor",
  "led",
  "n_channel_e_mosfet_transistor",
  "not_connected",
  "npn_bipolar_transistor",
  "opamp_no_power",
  "opamp_with_power",
  "p_channel_e_mosfet_transistor",
  "pnp_bipolar_transistor",
  "potentiometer",
  "rectifier_diode",
  "schottky_diode",
  "solderjumper2",
  "testpoint",
  "zener_diode",
];
const SUFFIXES = ["right", "up", "left", "down", "horz", "vert"];

const num = (v) => {
  const s = String(Math.round(v * 1e6) / 1e6);
  return s.includes(".") || s.includes("e") ? s : s + ".0";
};

const entries = [];
for (const base of BASES) {
  for (const suffix of SUFFIXES) {
    const name = `${base}_${suffix}`;
    const sym = symbols[name];
    if (!sym) continue;
    const ports = sym.ports.map((p) => ({
      dx: p.x - sym.center.x,
      dy: p.y - sym.center.y,
      labels: p.labels.map(String),
    }));
    entries.push({ name, w: sym.size.width, h: sym.size.height, ports });
  }
}
entries.sort((a, b) => (a.name < b.name ? -1 : 1));

let rs = `//! GENERATED by apps/desktop/tools/gen-symbol-geom.mjs — do not edit.
//! Regenerate with \`pnpm gen:symbol-geom\` after bumping schematic-symbols.
//! Port offsets are center-relative in the symbol's native coordinate space;
//! the emitter owns the world-space sign convention.

pub(crate) struct SymPort {
    pub(crate) dx: f64,
    pub(crate) dy: f64,
    pub(crate) labels: &'static [&'static str],
}

pub(crate) struct SymGeom {
    pub(crate) name: &'static str,
    pub(crate) w: f64,
    pub(crate) h: f64,
    pub(crate) ports: &'static [SymPort],
}

/// Sorted by name for binary search.
pub(crate) static SYMBOLS: &[SymGeom] = &[
`;
for (const e of entries) {
  const ports = e.ports
    .map(
      (p) =>
        `SymPort { dx: ${num(p.dx)}, dy: ${num(p.dy)}, labels: &[${p.labels
          .map((l) => JSON.stringify(l))
          .join(", ")}] }`,
    )
    .join(", ");
  rs += `    SymGeom { name: ${JSON.stringify(e.name)}, w: ${num(e.w)}, h: ${num(e.h)}, ports: &[${ports}] },\n`;
}
rs += `];

pub(crate) fn lookup(name: &str) -> Option<&'static SymGeom> {
    SYMBOLS
        .binary_search_by(|s| s.name.cmp(name))
        .ok()
        .map(|i| &SYMBOLS[i])
}
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== rs) {
    console.error(
      "symbol_geom.rs is out of date — run `pnpm gen:symbol-geom` and commit the result",
    );
    process.exit(1);
  }
  console.log(`symbol_geom.rs up to date (${entries.length} symbols)`);
} else {
  writeFileSync(OUT, rs);
  console.log(`wrote ${OUT} (${entries.length} symbols)`);
}
